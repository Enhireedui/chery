/* ---------- ТӨРЛҮҮД ---------- */

export interface Site {
  brandName: string;
  legal: string;
  role: string;
  phone: string;
  phoneHref: string;
  address: { line1: string; line2: string };
  /** [өдрийн нэр, цагийн хязгаар] */
  hours: Array<[string, string]>;
  geo: { lat: number; lng: number };
  mapLink: string;
  finance: { downPayment: string; term: string };
  warranty: { years: string; km: string };
}

export interface NavItem {
  href: string;
  label: string;
}

/** Нүүрний hero-гийн кадр. `img` нь `/assets/img/{img}.avif|webp`. */
export interface Slide {
  id: string;
  model: string;
  line: string;
  img: string;
  /** Кадрын байршил — зургийн `alt`-д орно. */
  scene: string;
}

export interface StoryItem {
  img: string;
  eyebrow: string;
  title: string;
  body: string;
}

export interface Color {
  name: string;
  en: string;
  hex: string;
  img: string;
}

/** Үзүүлэлтийн бүлэг. `rows` (хүснэгт) ЭСВЭЛ `list` (жагсаалт). */
export interface SpecGroup {
  group: string;
  /** [шошго, утга] эсвэл [шошго, утга1, утга2] — хоёр хувилбартай загварт */
  rows?: string[][];
  list?: string[];
  /** Хоёр хувилбартай загварын багануудын нэр (Tiggo 4: 1.5L / 1.5T) */
  cols?: string[];
}

export interface Panel {
  img: string;
  imgTall?: string;
  eyebrow: string;
  title: string;
  body?: string;
  dims?: Array<[string, string]>;
  note?: string;
}

export interface Model {
  id: string;
  name: string;
  segment: string;
  tagline: string;
  lede: string;
  /** `null` = үнэ нээлттэй зарлаагүй (Tiggo 7) — `priceShort` хэрэглэнэ */
  price?: { from: number; to?: number; note: string } | null;
  /** Үнэ нь «мэдээлэл авах» төлөвт байх загварт (Tiggo 7) */
  priceShort?: string;
  priceNote?: string;
  specsNote?: string;
  hero: string;
  heroTall?: string;
  card: string;
  /** Борлуулалтын брошюр — зөвхөн Tiggo 2-д байгаа */
  brochure?: { href: string; label: string; note: string };
  panels?: Panel[];
  /** [тоо, шошго]. `null` = үзүүлэлт баталгаажаагүй (Tiggo 7) */
  figures: Array<[string, string]> | null;
  story: StoryItem[];
  colors: Color[];
  /** Tiggo 7-д үзүүлэлт баталгаажаагүй тул `null` */
  specs: SpecGroup[] | null;
  gallery?: string[];
}

export interface Brand {
  figures: Array<[string, string]>;
  records: Array<[string, string, string]>;
  awards: Array<[string, string, string]>;
}

export interface Faq {
  q: string;
  a: string;
}

export interface TestDrive {
  title: string;
  lede: string;
  /** [гарчиг, тайлбар] */
  steps: Array<[string, string]>;
}

export interface Pillar {
  k: string;
  t: string;
  b: string;
}

/** Мэдээний нийтлэл. Одоогоор 0 — бодит мэдээ гарах хүртэл хоосон. */
export interface NewsItem {
  slug: string;
  title: string;
  date: string;
  lede: string;
  body?: string;
}

export interface Awards {
  lede: string;
  hero: { img: string; badge: string };
  ticker: string[];
  figures: Array<{ pre: string; to: number; dec: number; suf: string; label: string }>;
  global: Array<{ year: string; title: string; body: string; src: string }>;
  jdp: { lede: string; rows: Array<[string, string, string]> };
  byModel: Array<{ id: string; segment: string; tag?: string; list: string[] }>;
  records: Array<[string, string, string, string]>;
  markets: Array<[string, string, string, string]>;
  safety: Array<[string, string, string, string, string]>;
}

export interface CompareGroup {
  group: string;
  rows: Array<{
    label: string;
    /** Тогтмол утга (бүх загварт ижил) */
    from?: string;
    /** `specs`-ээс утгыг татах шошго. Массив бол аль нэг таарсныг авна. */
    pick?: string | string[];
  }>;
}

